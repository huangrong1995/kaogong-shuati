// 去掉 HTML 标签与全角空格；内容/解析缺省安全
function cleanText(s) {
  return String(s ?? '')
    .replace(/<[^>]*>/g, ' ')
    .replace(/　/g, '')
    .replace(/&nbsp;/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

// 在 FENBI_TREE 中按子模块名查找叶子数组（找不到 → undefined）
function findLeaves(sub) {
  if (!sub) return undefined;
  for (const group of FENBI_TREE) {
    for (const item of group.subs) {
      if (item.name === sub) return item.leaves;
    }
  }
  return undefined;
}

/**
 * 考点细分标签分类。
 * @param {{sub?: string, content?: string, analysis?: string}} input
 * @returns {string} 细分考点名；未命中或入参缺省 → '未细分'
 */
export function classifyLeaf({ sub, content = '', analysis = '' } = {}) {
  if (!sub) return '未细分';
  const text = cleanText(content) + '\n' + cleanText(analysis);

  const tags = LEAF_OVERRIDES[sub];
  if (tags) {
    const kw = TAG_KEYWORDS[sub];
    for (const tag of tags) {
      const kws = (kw && kw[tag]) || [tag];
      if (kws.some((k) => text.includes(k))) return tag;
    }
    return '未细分';
  }

  const leaves = findLeaves(sub);
  if (leaves) {
    for (const leaf of leaves) {
      const kws = FALLBACK_KEYWORDS[leaf] || [leaf];
      if (kws.some((k) => text.includes(k))) return leaf;
    }
  }
  return '未细分';
}

/**
 * 某子模块可产出的细分考点名单（供前端 / AI 展示）。
 * 有自定义标签 → 返回 LEAF_OVERRIDES[sub]；无 → 返回该子模块 FENBI leaves。
 */
export function leafTags(sub) {
  const tags = LEAF_OVERRIDES[sub];
  if (tags) return tags.slice();
  const leaves = findLeaves(sub);
  return leaves ? leaves.slice() : [];
}
